-- 002_cv_extension (PostgreSQL dialect) — schema support for CV population.
-- Transactional-safe: every statement is idempotent. Applied automatically as
-- part of scripts/cv-populate/populate.js and recorded here for fresh boots
-- (schema.postgres.sql mirrors these changes).

ALTER TABLE profile ADD COLUMN IF NOT EXISTS email TEXT;
ALTER TABLE profile ADD COLUMN IF NOT EXISTS location TEXT;
ALTER TABLE profile ADD COLUMN IF NOT EXISTS phone TEXT;
ALTER TABLE profile ADD COLUMN IF NOT EXISTS github TEXT;
ALTER TABLE profile ADD COLUMN IF NOT EXISTS portfolio TEXT;
ALTER TABLE profile ADD COLUMN IF NOT EXISTS linkedin TEXT;
CREATE UNIQUE INDEX IF NOT EXISTS uq_profile_email ON profile (email);

ALTER TABLE skill ADD COLUMN IF NOT EXISTS category TEXT;

ALTER TABLE experience ADD COLUMN IF NOT EXISTS is_current BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE experience ADD COLUMN IF NOT EXISTS location TEXT;

ALTER TABLE project ADD COLUMN IF NOT EXISTS deploy_url TEXT;
ALTER TABLE project ADD COLUMN IF NOT EXISTS profile_id BIGINT REFERENCES profile(id) ON DELETE CASCADE;

ALTER TABLE education ADD COLUMN IF NOT EXISTS grade TEXT;

CREATE TABLE IF NOT EXISTS person_skills (
    person_id BIGINT NOT NULL REFERENCES profile(id) ON DELETE CASCADE,
    skill_id BIGINT NOT NULL REFERENCES skill(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ DEFAULT now(),
    PRIMARY KEY (person_id, skill_id)
);

CREATE TABLE IF NOT EXISTS certifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    person_id BIGINT NOT NULL REFERENCES profile(id) ON DELETE CASCADE,
    title TEXT NOT NULL,
    issuer TEXT,
    created_at TIMESTAMPTZ DEFAULT now(),
    updated_at TIMESTAMPTZ DEFAULT now()
);

CREATE TABLE IF NOT EXISTS cv_references (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    person_id BIGINT NOT NULL REFERENCES profile(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    role TEXT,
    organization TEXT,
    email TEXT,
    phone TEXT,
    created_at TIMESTAMPTZ DEFAULT now()
);

CREATE TABLE IF NOT EXISTS recommendations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    person_id BIGINT NOT NULL REFERENCES profile(id) ON DELETE CASCADE,
    title TEXT NOT NULL,
    issuer TEXT,
    created_at TIMESTAMPTZ DEFAULT now(),
    updated_at TIMESTAMPTZ DEFAULT now()
);

CREATE TABLE IF NOT EXISTS population_warnings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    table_name TEXT NOT NULL,
    column_name TEXT,
    reason TEXT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT now()
);

DROP TRIGGER IF EXISTS trg_certifications_updated_at ON certifications;
CREATE TRIGGER trg_certifications_updated_at
BEFORE UPDATE ON certifications
FOR EACH ROW EXECUTE FUNCTION set_updated_at();

DROP TRIGGER IF EXISTS trg_recommendations_updated_at ON recommendations;
CREATE TRIGGER trg_recommendations_updated_at
BEFORE UPDATE ON recommendations
FOR EACH ROW EXECUTE FUNCTION set_updated_at();
